"""Write prices.yaml from a saved copy of TokenRouter's public catalogue.

Usage: python tools/gen_prices.py <pricing.json> <out prices.yaml>
The catalogue is GET https://api.tokenrouter.com/api/pricing (no key). Rule: rj/pricing.py.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from rj.pricing import est_session_usd, price_from_ratios  # noqa: E402

# model id in matrix.yaml -> slug on TokenRouter
MODELS = {
    "claude-haiku-4.5": "anthropic/claude-haiku-4.5",
    "kimi-k2.7-code": "moonshotai/kimi-k2.7-code",
    "gpt-5.4-mini": "openai/gpt-5.4-mini",
    "qwen3.7-plus": "qwen/qwen3.7-plus",
    "claude-sonnet-5.5": "anthropic/claude-sonnet-5.5",
    "claude-sonnet-4.6": "anthropic/claude-sonnet-4.6",
    "gpt-5.4": "openai/gpt-5.4",
    "qwen3.7-max": "qwen/qwen3.7-max",
    "deepseek-v4-pro": "deepseek/deepseek-v4-pro",
    "gpt-5.6-terra": "openai/gpt-5.6-terra",
    "claude-opus-5.5": "anthropic/claude-opus-5.5",
    "gpt-6.2-sol": "openai/gpt-6.2-sol",
}
JUDGES = {
    "gemini-3-flash-preview": "google/gemini-3-flash-preview",
    "gemini-3.7-flash": "google/gemini-3.7-flash",
}
# A judge asked at its vendor (`judge.provider: anthropic`) is not in TokenRouter's catalogue. Its line is written as
# it stands here: the vendor's model id and list price, USD per million tokens.
DIRECT_JUDGES = {
    "claude-opus-5.5": "{slug: claude-opus-5-5, input: 4, cache_read: 0.2, cache_write: 5, output: 20}",
}


def num(x: float) -> str:
    return repr(round(x, 6)).rstrip("0").rstrip(".") if "." in repr(round(x, 6)) else repr(round(x, 6))


def main(src: str, out: str) -> None:
    data = {r["model_name"]: r for r in json.loads(Path(src).read_text())["data"]}
    lines = [
        "# USD per million tokens. Generated by tools/gen_prices.py from TokenRouter's public catalogue",
        "# (input = model_ratio x 2; the dollar unit is inferred until check 11 measures a session).",
        "# est_session_usd assumes 0.9M uncached input, 5.1M cache reads and 0.06M output tokens.",
        "tokenrouter:",
    ]
    for model, slug in MODELS.items():
        p = price_from_ratios(data[slug])
        lines.append(
            f"  {model}: {{slug: {slug}, input: {num(p.input)}, cache_read: {num(p.cache_read)}, "
            f"cache_write: {num(p.cache_write)}, output: {num(p.output)}, est_session_usd: {est_session_usd(p)}}}"
        )
    lines.append("judge:")
    for model, slug in JUDGES.items():
        p = price_from_ratios(data[slug])
        lines.append(f"  {model}: {{slug: {slug}, input: {num(p.input)}, cache_read: {num(p.cache_read)}, output: {num(p.output)}}}")
    lines += [f"  {model}: {entry}" for model, entry in DIRECT_JUDGES.items()]
    lines += [
        "agent_work: {usd_per_active_minute: 0.020, free: null}     # free is set by check 9",
        "measured: {}     # <row>: {session_usd, minutes, input_includes_cache}, written by check 11",
        "",
    ]
    Path(out).write_text("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
